#!/usr/bin/env python3
"""Grows tools/sim/elvui/Shim.lua: the sandbox-only stubs that let ElvUI (+ ElvUI_WC3) load in wow-ui-sim, which
lacks some client APIs. Error-driven, after ~/Projects/elvui-wc3/tools/sim/grow_shim.py: render the ElvUI scene,
collect "attempt to index/call global/method X" errors raised in ElvUI, oUF or WC3 files, add a stub for X, repeat.
The shim is never installed in the game; our addon's code is unchanged by it.
usage: python3 tools/sim/grow_elvui_shim.py [max_iters]
"""
import glob, json, os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
STATE = os.path.join(ROOT, "tools", "sim", "elvui", "shim_names.json")
SHIM = os.path.join(ROOT, "tools", "sim", "elvui", "Shim.lua")
TMP = os.path.expanduser("~/.cache/rested-leveling/tmp")
FILES = r"(?:ElvUI[^ :]*|oUF[^ :]*|WC3[^ :]*|LibElvUIPlugin[^ :]*|Ace[^ :]*)\.lua:\d+: "
PAT = re.compile(FILES + r"attempt to (index|call) (global|method|field|upvalue) '([A-Za-z_][A-Za-z0-9_]*)' \(a nil value\)")

# Value-returning stubs where nil would break the caller (from the ElvUI_WC3 sim work).
DEFAULTS = {
    "UnitSelectionType": "function() return 0 end", "UnitHasPowerType": "function() return true end",
    "UnitInPhase": "function() return true end", "UnitIsMercenary": "function() return false end",
    "IsChatAFK": "function() return false end", "IsChatDND": "function() return false end",
    "GetNumTalentGroups": "function() return 1 end", "GetNumBankSlots": "function() return 0, false end",
    "issecrettable": "function() return false end", "canaccesstable": "function() return true end",
    "canaccessvalue": "function() return true end", "canaccesssecrets": "function() return true end",
}


def load():
    if os.path.exists(STATE):
        return json.load(open(STATE))
    return {"tables": [], "funcs": [], "methods": []}


def write(names):
    L = ["-- GENERATED by tools/sim/grow_elvui_shim.py. Offline render sandbox only: never installed in the game.",
         "-- Stubs for client APIs wow-ui-sim lacks, so ElvUI and ElvUI_WC3 load. Missing members of any C_ namespace",
         "-- resolve to a no-op.",
         "local noop = function() end",
         "local function soft(t) if type(t) == 'table' and getmetatable(t) == nil then",
         "  setmetatable(t, { __index = function() return noop end }) end end"]
    for t in sorted(names["tables"]):
        L.append("if rawget(_G, %r) == nil then _G[%r] = {} end" % (t, t))
    L.append("for k, v in pairs(_G) do if type(k) == 'string' and k:match('^C_') then soft(v) end end")
    for t in sorted(names["tables"]):
        L.append("soft(_G[%r])" % t)
    for f in sorted(names["funcs"]):
        L.append("if rawget(_G, %r) == nil then _G[%r] = %s end" % (f, f, DEFAULTS.get(f, "noop")))
    # ElvUI settings for the render (ElvUI's own saved data, sandbox only): a readable UI scale.
    L += ["ElvDB = ElvDB or { global = { general = { UIScale = 1.0 } } }",
          "-- Skip ElvUI's first-run install wizard: this character has finished it.",
          "ElvPrivateDB = ElvPrivateDB or { profileKeys = setmetatable({}, { __index = function() return 'Default' end }),",
          "  profiles = { Default = { install_complete = 99 } } }"]
    # Known gaps with values that matter (from the ElvUI_WC3 sim work, gen_shim.py).
    L += ["do local t = rawget(_G, 'C_Secrets') or {}; _G.C_Secrets = t",
          "  if t.CanCompareUnitTokens == nil then t.CanCompareUnitTokens = function() return true end end",
          "  if t.ShouldUnitIdentityBeSecret == nil then t.ShouldUnitIdentityBeSecret = function() return false end end end",
          "if ColorMixin and not ColorMixin.SetRGBA then ColorMixin.SetRGBA = function(self, r, g, b, a) self.r, self.g, self.b, self.a = r, g, b, a end end",
          "if type(DebuffTypeColor) == 'table' and ColorMixin and Mixin then for _, c in pairs(DebuffTypeColor) do",
          "  if type(c) == 'table' and not c.SetRGBA then Mixin(c, ColorMixin) end end end"]
    # LibDispel's colour tables are plain tables in the sim; ElvUI calls :SetRGBA on them when a profile changes.
    L += ["local fixer = CreateFrame('Frame'); fixer:RegisterEvent('ADDON_LOADED')",
          "fixer:SetScript('OnEvent', function() local L = LibStub and LibStub('LibDispel-1.0', true)",
          "  if L and L.GetDebuffTypeColor then for _, c in pairs(L:GetDebuffTypeColor() or {}) do",
          "    if type(c) == 'table' and not c.SetRGBA then c.SetRGBA = function(self, r, g, b, a) self.r, self.g, self.b, self.a = r, g, b, a end end",
          "  end end end)"]
    L.append("local SIM_METHODS = {" + ", ".join("%r" % m for m in sorted(names["methods"])) + "}")
    L.append("""local seen = {}
for _, ty in ipairs({ 'Frame', 'Button', 'CheckButton', 'StatusBar', 'Slider', 'EditBox', 'ScrollFrame', 'Cooldown',
  'GameTooltip', 'MessageFrame', 'ScrollingMessageFrame', 'Model', 'PlayerModel', 'ColorSelect' }) do
  local ok, f = pcall(CreateFrame, ty)
  if ok and f then
    local objs = { f }
    if f.CreateTexture then objs[#objs + 1] = f:CreateTexture(); objs[#objs + 1] = f:CreateFontString() end
    if f.CreateAnimationGroup then local ag = f:CreateAnimationGroup(); objs[#objs + 1] = ag; objs[#objs + 1] = ag:CreateAnimation('Alpha') end
    for _, o in pairs(objs) do
      local mt = getmetatable(o)
      local idx = mt and mt.__index
      if type(idx) == 'table' and not seen[idx] then
        seen[idx] = true
        for _, m in ipairs(SIM_METHODS) do if idx[m] == nil then pcall(function() idx[m] = noop end) end end
      end
    end
  end
end""")
    open(SHIM, "w").write("\n".join(L) + "\n")


def run():
    out = os.path.join(TMP, "grow")
    for d in glob.glob(os.path.join(TMP, "render.*")):
        subprocess.run(["chmod", "-R", "u+w", d])
        shutil.rmtree(d, ignore_errors=True)
    env = dict(os.environ, RL_KEEP="1")
    subprocess.run([os.path.join(ROOT, "tools", "render.sh"), out, "02"], env=env, capture_output=True, text=True)
    logs = glob.glob(os.path.join(TMP, "render.*", "02_main_elvui", "sim.log"))
    return open(logs[0], errors="ignore").read() if logs else ""


def main():
    iters = int(sys.argv[1]) if len(sys.argv) > 1 else 15
    names = load()
    log = ""
    for i in range(iters):
        write(names)
        log = run()
        new = {"tables": set(), "funcs": set(), "methods": set()}
        for how, kind, name in PAT.findall(log):
            if kind == "method":
                new["methods"].add(name)
            elif kind in ("global", "upvalue"):   # an upvalue is a global captured as a local at load
                new["tables" if how == "index" else "funcs"].add(name)
        new = {k: v - set(names[k]) for k, v in new.items()}
        print("iter %d: %s" % (i, {k: sorted(v) for k, v in new.items() if v}), flush=True)
        if not any(new.values()):
            break
        for k, v in new.items():
            names[k] = sorted(set(names[k]) | v)
        json.dump(names, open(STATE, "w"), indent=1)
    errs = re.findall(r"Lua (?:E|e)rror: [^\n]*(?:ElvUI|oUF|WC3)[^\n]{0,220}", log)
    seen = []
    for e in errs:
        if e not in seen:
            seen.append(e)
    for e in seen[:15]:
        print("  ", e[:260])


if __name__ == "__main__":
    main()
